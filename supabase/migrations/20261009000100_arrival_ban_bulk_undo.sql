-- Undoing a manual wallet adjustment deletes its transaction. Reverse the
-- balance delta on deletion too, while sales continue to add compensating rows.
create or replace function public.apply_wallet_transaction()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if tg_op = 'INSERT' then
    update public.wallet_balances set balance = balance + new.amount, updated_at = now() where bucket = new.bucket;
    return new;
  end if;
  update public.wallet_balances set balance = balance - old.amount, updated_at = now() where bucket = old.bucket;
  return old;
end $$;
drop trigger if exists trg_apply_wallet_transaction on public.wallet_transactions;
create trigger trg_apply_wallet_transaction after insert or delete on public.wallet_transactions
  for each row execute function public.apply_wallet_transaction();

-- Undo all rows written by the most recent transaction, up to ten recent
-- transactions remain available in the UI. Replaying skips new undo records.
create or replace function public.undo_latest_action()
returns text language plpgsql security definer set search_path = public as $$
declare
  latest_event public.undo_events;
  e public.undo_events;
  target uuid;
  assignments text;
begin
  select * into latest_event
    from public.undo_events
   where user_id = auth.uid() and undone_at is null and expires_at > now()
   order by event_order desc limit 1 for update;
  if not found then raise exception 'Nothing to undo'; end if;
  perform set_config('project26.undo_replay', 'on', true);

  for e in
    select * from public.undo_events
     where user_id = auth.uid() and undone_at is null and expires_at > now()
       and ((latest_event.transaction_id is not null and transaction_id = latest_event.transaction_id)
         or (latest_event.transaction_id is null and id = latest_event.id))
     order by event_order desc for update
  loop
    if e.table_name not in ('inventory_items','packages','marketplace_accounts','sales','trades','closet_items','chapters','closet_sections','posting_accounts','item_postings','platforms','wallet_transactions') then
      raise exception 'This change cannot be undone safely';
    end if;
    target := coalesce((e.row_after->>'id')::uuid, (e.row_before->>'id')::uuid);
    if e.operation = 'INSERT' then
      execute format('delete from public.%I where id = $1', e.table_name) using target;
    elsif e.operation = 'DELETE' then
      execute format('insert into public.%I select * from jsonb_populate_record(null::public.%I, $1)', e.table_name, e.table_name) using e.row_before;
    else
      select string_agg(format('%I = (jsonb_populate_record(null::public.%I, $2)).%I', column_name, e.table_name, column_name), ', ')
        into assignments
        from information_schema.columns
       where table_schema = 'public' and table_name = e.table_name and column_name <> 'id';
      execute format('update public.%I set %s where id = $1', e.table_name, assignments) using target, e.row_before;
    end if;
    update public.undo_events set undone_at = now() where id = e.id;
  end loop;
  return latest_event.table_name || ' transaction';
end $$;
grant execute on function public.undo_latest_action() to authenticated;

create or replace function public.undo_available_count()
returns integer language sql security definer set search_path = public as $$
  select least(count(distinct coalesce('tx:' || transaction_id::text, 'event:' || id::text)), 10)::integer
    from public.undo_events
   where user_id = auth.uid() and undone_at is null and expires_at > now();
$$;
grant execute on function public.undo_available_count() to authenticated;
