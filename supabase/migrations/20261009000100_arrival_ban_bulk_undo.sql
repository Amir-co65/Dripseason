-- Reset a banned marketplace account's posting records within the same
-- transaction. Match both explicit links and legacy numbered accounts.
create or replace function public.reset_postings_for_banned_account()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if new.banned and not old.banned then
    update public.item_postings ip
       set status = 'needs_posting', posting_account_id = null
     where ip.posting_account_id in (
       select pa.id
         from public.posting_accounts pa
        where pa.marketplace_account_id = new.id
           or (new.posting_account_number is not null
               and pa.platform = new.platform
               and pa.account_number = new.posting_account_number)
     );
  end if;
  return new;
end $$;
drop trigger if exists trg_reset_postings_for_banned_account on public.marketplace_accounts;
create trigger trg_reset_postings_for_banned_account
  after update of banned on public.marketplace_accounts
  for each row execute function public.reset_postings_for_banned_account();

-- Bulk posting updates run as one database transaction, so a single Undo
-- restores the whole search result set.
create or replace function public.set_item_postings_bulk(
  p_inventory_item_ids uuid[], p_platform_slug text, p_status text, p_posting_account_id uuid
) returns integer language plpgsql set search_path = public as $$
declare affected integer;
begin
  if auth.uid() is null then raise exception 'Authentication required'; end if;
  if p_status not in ('needs_posting', 'skipped', 'posted') then raise exception 'Invalid posting status'; end if;
  if not exists (select 1 from public.platforms where slug = p_platform_slug and is_active) then raise exception 'Platform is not active'; end if;
  if p_status = 'posted' and (p_posting_account_id is null or not exists (
    select 1 from public.posting_accounts pa
     where pa.id = p_posting_account_id and pa.platform = p_platform_slug
       and not exists (
         select 1 from public.marketplace_accounts ma
          where ma.banned and (ma.id = pa.marketplace_account_id
            or (ma.platform = pa.platform and ma.posting_account_number = pa.account_number))
       )
  )) then raise exception 'Choose a posting account for this platform'; end if;

  insert into public.item_postings (inventory_item_id, platform_slug, status, posting_account_id)
  select distinct item_id, p_platform_slug, p_status,
         case when p_status = 'posted' then p_posting_account_id else null end
    from unnest(p_inventory_item_ids) as selected(item_id)
   where item_id is not null
  on conflict (inventory_item_id, platform_slug) do update
    set status = excluded.status, posting_account_id = excluded.posting_account_id;
  get diagnostics affected = row_count;
  return affected;
end $$;
grant execute on function public.set_item_postings_bulk(uuid[], text, text, uuid) to authenticated;

-- Keep the latest user changes as reversible transaction groups. This
-- includes posting, closet, chapter, and app changes that were not captured
-- by the original Undo triggers.
alter table public.undo_events add column if not exists transaction_id bigint;
alter table public.undo_events add column if not exists event_order bigint generated by default as identity;
create index if not exists idx_undo_events_user_recent on public.undo_events(user_id, event_order desc)
  where undone_at is null;

create or replace function public.capture_undo()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if current_setting('project26.undo_replay', true) = 'on' or auth.uid() is null then
    return coalesce(new, old);
  end if;
  -- Sale and account balance transactions are derived from their parent
  -- records and must be reversed by those parent actions.
  if tg_table_name = 'wallet_transactions' then
    if coalesce(new.related_sale_id, old.related_sale_id) is not null
       or coalesce(new.reason, old.reason) not in ('Wallet add', 'Wallet take', 'Set balance') then
      return coalesce(new, old);
    end if;
  end if;
  insert into public.undo_events(user_id, table_name, operation, row_before, row_after, transaction_id)
  values(auth.uid(), tg_table_name, tg_op,
         case when tg_op <> 'INSERT' then to_jsonb(old) end,
         case when tg_op <> 'DELETE' then to_jsonb(new) end,
         txid_current());
  return coalesce(new, old);
end $$;

